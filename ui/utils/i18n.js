function formatTemplate(template, params = {}) {
  return template.replace(/\{(\w+)\}/g, (_, key) => params[key] ?? `{${key}}`);
}

export class I18n {
  constructor() {
    this.locale = this.getSavedLocale() || this.detectLocale();
    this.listeners = [];
  }

  init(options = {}) {
    this.ensureDocumentLanguage();
    this.createSelector(options.selectorTarget);
    this.applyTranslations();
  }

  ensureDocumentLanguage() {
    document.documentElement.setAttribute('lang', this.locale);
  }

  detectLocale() {
    const lang = navigator.language?.toLowerCase() || 'en';
    if (lang.startsWith('pt')) return 'pt-BR';
    if (lang.startsWith('pl')) return 'pl';
    return 'en';
  }

  getSavedLocale() {
    try {
      const locale = localStorage.getItem('ruview-locale');
      if (locale === 'pt' || locale === 'pt-br') return 'pt-BR';
      return locale;
    } catch {
      return null;
    }
  }

  saveLocale(locale) {
    try {
      localStorage.setItem('ruview-locale', locale);
    } catch {
      // noop
    }
  }

  t(key, params) {
    const dict = translations[this.locale] || translations.en;
    const template = dict[key] || translations.en[key] || key;
    return params ? formatTemplate(template, params) : template;
  }

  setLocale(locale) {
    if (locale === 'pt' || locale === 'pt-br') locale = 'pt-BR';
    if (!translations[locale]) return;
    this.locale = locale;
    this.saveLocale(locale);
    this.ensureDocumentLanguage();
    this.applyTranslations();
    this.listeners.forEach(cb => {
      try {
        cb(locale);
      } catch {
        // noop
      }
    });
  }

  onLocaleChange(callback) {
    this.listeners.push(callback);
    return () => {
      const index = this.listeners.indexOf(callback);
      if (index > -1) this.listeners.splice(index, 1);
    };
  }

  applyTranslations(root = document) {
    root.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      el.textContent = this.t(key);
    });

    root.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      el.innerHTML = this.t(key);
    });

    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.placeholder = this.t(key);
    });

    root.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const key = el.getAttribute('data-i18n-aria');
      el.setAttribute('aria-label', this.t(key));
    });

    root.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      el.setAttribute('title', this.t(key));
    });

    const titleEl = document.querySelector('title[data-i18n]');
    if (titleEl) titleEl.textContent = this.t(titleEl.getAttribute('data-i18n'));

    const selector = document.getElementById('lang-selector');
    if (selector) selector.value = this.locale;
  }

  createSelector(targetSelector = '.header-info') {
    if (!targetSelector) return;
    if (document.getElementById('lang-selector')) return;

    const target = typeof targetSelector === 'string'
      ? document.querySelector(targetSelector)
      : targetSelector;
    if (!target) return;

    const wrapper = document.createElement('div');
    wrapper.className = 'lang-selector-wrap';
    wrapper.style.pointerEvents = 'auto';
    wrapper.innerHTML = `
      <select id="lang-selector" class="lang-selector" aria-label="${this.t('misc.language')}">
        <option value="en">EN</option>
        <option value="pl">PL</option>
        <option value="pt-BR">PT-BR</option>
      </select>
    `;

    const select = wrapper.querySelector('select');
    select.style.pointerEvents = 'auto';
    select.value = this.locale;
    select.addEventListener('change', () => this.setLocale(select.value));
    target.appendChild(wrapper);
  }

  getAvailableLocales() {
    return Object.keys(translations);
  }

  dispose() {
    this.listeners = [];
  }
}

export const i18n = new I18n();
